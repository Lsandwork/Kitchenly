/** Local hero image path for every owned recipe. */
export function recipeImagePath(slug: string) {
  return `/assets/recipes/${slug}.jpg`;
}

/** Ensure every owned recipe points at a local hero image. */
export function withRecipeImages(recipes: RecipeRecord[]): RecipeRecord[] {
  return recipes.map((recipe) => ({
    ...recipe,
    imageUrl: recipe.imageUrl || recipeImagePath(recipe.slug),
  }));
}

